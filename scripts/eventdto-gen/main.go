const (
	protoPath = "api/proto/events/v1/microlease_events.proto"
	outPath   = "internal/api/events/v1/microlease_events.gen.go"
)

var requiredMessages = []string{
	"MicroleaseEventEnvelope",
	"PricingSnapshotBasis",
	"MicroleaseIdentity",
	"MicroleaseChildTerminalSubmitted",
	"MicroleaseCheckpointReported",
	"MicroleaseCloseReported",
	"MicroleaseIssued",
	"MicroleaseTerminalApplied",
	"MicroleaseClosed",
	"MicroleaseAdmissionRejected",
}

func main() {
	proto, err := os.ReadFile(protoPath)
	if err != nil {
		fatalf("read proto: %v", err)
	}
	for _, message := range requiredMessages {
		if !strings.Contains(string(proto), "message "+message+" ") {
			fatalf("proto is missing required message %s", message)
		}
	}

	sum := sha256.Sum256(proto)
	source := render(hex.EncodeToString(sum[:]))
	formatted, err := format.Source(source)
	if err != nil {
		fatalf("format generated source: %v", err)
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o750); err != nil {
		fatalf("create output directory: %v", err)
	}
	if err := os.WriteFile(outPath, formatted, 0o600); err != nil {
		fatalf("write generated DTOs: %v", err)
	}
}

